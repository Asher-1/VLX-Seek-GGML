#!/usr/bin/env python3
"""Regenerate src/task_templates.inc from vlx_seek/task_templates.py.

The C++ chain must build byte-identical prompts, so the templates are not
retyped by hand: this script emits every (lang, task) template as an escaped
C string literal. Rerun whenever the upstream template file changes.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from vlx_seek.task_templates import VLX_SEEK_1_5  # noqa: E402


def c_literal(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif 0x20 <= b < 0x7F and b != 0x3F:   # '?' escaped: no trigraphs
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")           # octal: never swallows a following hex digit
    return '"' + "".join(out) + '"'


def main() -> None:
    lines = ["// GENERATED by scripts/gen_task_templates.py from vlx_seek/task_templates.py",
             "// -- do not edit. {lang, task, template-with-one-{}-slot}"]
    for lang, table in VLX_SEEK_1_5.items():
        for task, tpl in table.items():
            assert tpl.count("{}") == 1, (lang, task)
            lines.append(f'{{"{lang}", "{task}", {c_literal(tpl)}}},')
    out = ROOT / "cpp_ggml/src/task_templates.inc"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({sum(len(t) for t in VLX_SEEK_1_5.values())} templates)")


if __name__ == "__main__":
    main()
